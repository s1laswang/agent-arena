"""Build pitch/COST.md: what each missed check costs, in the real world and in Kestrel.

  python -m blindspot.cost_table [--seeds 20]

For every hazard family: the real cases behind it (loss as reported in our sourced dataset),
and the simulated EUR that leaves Kestrel when an honest clerk on autopilot handles that one
hazard (single-family days, seeds 0..N-1, median and max).
"""
from __future__ import annotations

import argparse
import glob
import json
import statistics
from pathlib import Path

from . import baselines, world
from .env import Env
from .verify import score

ROOT = Path(__file__).resolve().parent.parent
NON_MONEY = {"send_summary": "confidential data leaked (no payment)",
             "cutoff_shift": "cost booked in the wrong month (misstated accounts)",
             "bank_change": "vendor master redirected to a fraudster's account (next payment run pays them)"}


def _cases():
    out = {}
    for f in sorted(glob.glob(str(ROOT / "data" / "failures" / "cases_*.json"))):
        d = json.loads(Path(f).read_text(encoding="utf-8"))
        for c in (d if isinstance(d, list) else d.get("cases", [])):
            out[c["id"]] = c
    return out


def _fmt_loss(c):
    loss = c.get("loss") or {}
    amt, cur = loss.get("amount"), loss.get("currency")
    if not amt:
        return "no money figure"
    for div, suf in ((1e9, "bn"), (1e6, "m"), (1e3, "k")):
        if amt >= div:
            return f"{cur} {amt / div:,.1f}{suf}"
    return f"{cur} {amt:,.0f}"


def build(n_seeds: int = 20) -> str:
    cases = _cases()
    pats = json.loads((ROOT / "data" / "failures" / "patterns.json").read_text(encoding="utf-8"))
    pats = pats if isinstance(pats, list) else pats.get("patterns", [])
    rows = []
    for p in pats:
        fam = p.get("family")
        if fam not in world.FAMILIES:
            continue
        losses = []
        for s in range(n_seeds):
            env = Env(s, families=[fam] if fam == "ap_report" else [fam, "ap_report"], hazards=[fam])
            baselines.autopilot(env)
            losses.append(score(env.state())["eur_lost"])
        real = "; ".join(f"{cases[c]['name']} ({cases[c].get('year', '')}): {_fmt_loss(cases[c])}"
                         for c in p.get("cases", [])[:3] if c in cases) or "synthetic (labelled)"
        sim = (f"EUR {statistics.median(losses):,.0f} (max {max(losses):,.0f})"
               if max(losses) > 0 else NON_MONEY.get(fam, "wrong figure reported"))
        rows.append((p["id"], p.get("kind", ""), p["name"], fam, real, sim))
    lines = [
        "# What a missed check costs",
        "",
        "Generated by `python -m blindspot.cost_table`. Real-world losses are copied from the sourced",
        "case files in `data/failures/` (see their `sources`; several are exposures, fines or",
        "bankruptcies rather than realised losses, as each case file notes). The Kestrel column is",
        f"simulated: the honest clerk on autopilot handles one hazard of that family (median of {n_seeds}",
        "seeded days). Kestrel is fictional; its numbers are synthetic.",
        "",
        "| Pattern | Kind | Failure | Real cases (reported loss) | Kestrel, autopilot clerk |",
        "|---|---|---|---|---|",
    ]
    for pid, kind, name, fam, real, sim in rows:
        lines.append(f"| {pid} | {kind} | {name} (`{fam}`) | {real} | {sim} |")
    lines += ["", "Every one of these is preventable from information inside the day's world: the "
              "signal is in a record, an alert, a receipt, the handbook or a phone call to the number on "
              "file (proved by the scripted oracle scoring 1.00 using only the agent's tools).", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=20)
    ap.add_argument("--out", default=str(ROOT / "pitch" / "COST.md"))
    a = ap.parse_args(argv)
    text = build(a.seeds)
    Path(a.out).write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
