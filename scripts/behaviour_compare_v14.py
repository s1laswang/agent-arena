"""How do the reference solver, gpt-5.5 and gemini-4-carbon PLAY the same v1.4 hard seeds (0-29)?

Reads only committed episodes and prints one markdown table: canaries planted, interviews, accusation day, accuracy,
score. No model calls. Usage:
    python scripts/behaviour_compare_v14.py [--out results/behaviour_compare_v1.4.md]
"""
from __future__ import annotations

import argparse
import collections
import glob
import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
V14 = ROOT / "data" / "runs" / "committed" / "v1.4"
SEEDS = set(range(30))
AGENTS = [
    ("reference solver", "reference/solver-hard-*", "solver"),
    ("gpt-5.5, OpenCode over MCP", "opencode-gpt-5.5/hard", "opencode:openai/gpt-5.5"),
    ("gemini-4-carbon, OpenCode over MCP", "opencode-gemini-4-carbon/hard", "opencode:google/gemini-4-carbon"),
]


def load(pattern: str, agent: str) -> dict[int, dict]:
    out: dict[int, dict] = {}
    for f in sorted(glob.glob(str(V14 / pattern / "episodes.jsonl"))):
        for line in open(f):
            e = json.loads(line)
            if e.get("agent") == agent and e.get("tier") == "hard" and e.get("seed") in SEEDS \
                    and (e.get("meta") or {}).get("valid") is not False:
                out[e["seed"]] = e
    return out


def row(label: str, eps: dict[int, dict]) -> dict:
    n = len(eps)
    tools = [collections.Counter(s["tool"] for s in e.get("steps", [])) for e in eps.values()]
    calls = [sum(c.values()) for c in tools]
    accused = [e for e in eps.values() if e.get("accused")]
    days = [e.get("final_day") or 0 for e in accused]
    return {
        "agent": label, "n": n,
        "score": st.mean(e["score"] for e in eps.values()),
        "canaries": st.mean(c.get("plant_canary", 0) for c in tools),
        "interviews": st.mean(c.get("interview", 0) for c in tools),
        "interview_share": sum(c.get("interview", 0) for c in tools) / max(1, sum(calls)),
        "calls": st.mean(calls),
        "accuse_day": st.mean(days) if days else float("nan"),
        "accused": len(accused), "correct": sum(1 for e in accused if e.get("correct")),
        "wrong": sum(1 for e in accused if not e.get("correct")), "none": n - len(accused),
    }


def render(rows: list[dict]) -> str:
    out = ["# How three agents play the same v1.4 hard seeds (0-29)",
           "",
           "Generated by `python scripts/behaviour_compare_v14.py` from committed, replay-verified episodes "
           "(`data/runs/committed/v1.4/`). Means are per episode. Same tools and v1.4 rules; the later GPT run includes the disclosed wording and error-detail clarification.",
           "",
           "| agent | n | score | canaries planted | interviews | share of calls that are interviews | tool calls "
           "| accusation day | correct / wrong / no accusation |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---|"]
    for r in rows:
        out.append(f"| {r['agent']} | {r['n']} | {r['score']:+.3f} | {r['canaries']:.1f} | {r['interviews']:.1f} | "
                   f"{100 * r['interview_share']:.0f}% | {r['calls']:.0f} | {r['accuse_day']:.1f} | "
                   f"{r['correct']} / {r['wrong']} / {r['none']} |")
    out += ["",
            "Reading: gpt-5.5 plays the canary trap the way the reference does (about two canaries a day, almost no "
            "interviews) and matches its score. gemini-4-carbon spends most of its calls on interviews, whose stated "
            "likelihood ratio is 1.2, plants about half as many canaries and accuses about three days later, with more "
            "wrong accusations. The later GPT run used the disclosed wording clarification; this is a behavioral comparison, not a causal isolation of model identity.",
            ""]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    rows = [row(label, load(pat, agent)) for label, pat, agent in AGENTS]
    text = render(rows)
    if a.out:
        Path(a.out).write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
